# ===================================================================
# ★ 数据分层与增量抓取配置（2026-09-21 新增）
# ===================================================================
#
# 【为什么要分 ODS】
# 改造前，抓到的岗位直接写进 jobs 表，用 UNIQUE(company,title) +
# INSERT OR IGNORE 去重。这其实是「幂等覆盖」，不是「数据源」，三个问题：
#   1. 丢历史：岗位改了薪资、改了截止时间、下架了，库里看不出来——
#      重复记录被 IGNORE 跳过，永远是第一次抓到的那个样子。
#   2. 无口径：分不清「这条是新岗位」还是「三天前就抓到的老岗位」，
#      因此回答不了「最近一周新增了哪些岗位」。
#   3. 不能增量：每次都得把几百个详情页重新抓一遍（每页节流 1.6 秒，
#      全量约 8 分钟），而其中绝大多数内容根本没变。
#
# 现在改成三层，各管一件事：
#
#   ODS（贴源层）    ods_job_snapshot / ods_crawl_batch
#       每次抓取的原始结果原样追加，只增不改不删。职责是「如实记录」，
#       不做任何业务加工。它同时是增量抓取时回填字段的来源。
#   DWD（最新状态层）  jobs
#       每个职位一条最新状态 + 生命周期字段（首见/末见/变更次数/在架）。
#       职责是「当前长什么样」，供筛选与导出使用。
#   ADS（应用层）    output/*.xlsx
#       按筛选条件导出的岗位清单。
#
# 分层的直接收益：原始数据永不丢失，任何加工都能重跑（改打分规则重算、
# 改口径重筛），不会因为一次误操作导致不可恢复。

# 数据源标识，用作 job_key 前缀（如 xmu:2401083）。
# 为什么要前缀：将来接入第二个站点时，两站的职位 ID 可能撞号，

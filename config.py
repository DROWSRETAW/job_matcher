# ============ 匹配度打分配置 ============
#
# 【打分模型 v2 · 2026-09-20 重构】
#
# v1 的问题是「一键词表加权求和」，实测暴露三个系统性偏差：
#   1. 「不限专业」得 0 分 —— 把「无门槛」编码成了「不匹配」，
#      导致中行信息科技岗、浩鲸云计算开发工程师等 8 个技术岗被直接扔掉
#   2. 分数与「专业罗列数量」正相关：客户服务岗（列 48 个专业）53 分，
#      排在数据分析管培生（35 分）前面 —— 逻辑反了。
#      一家公司把专业写 40 个，恰恰说明它对专业**没有偏好**，是弱信号，
#      但 v1 按「命中 9 个词」累加了 9 次
#   3. 专业字段抓取失败（14 条，4.9%）被静默当成「不匹配」，
#      而不是「数据缺失」——与项目内第 5 号调试记录同类型错误
#
# v2 把打分拆成两个**语义独立**的通道：
#
#   总分 = 岗位方向分（标题） + 专业准入分（专业字段，含专指度衰减） - 反向词扣分
#
#   · 岗位方向分回答「这个岗位是不是我要投的方向」→ 只看岗位名称
#   · 专业准入分回答「我的专业能不能过这道门槛」→ 只看专业要求
#
# 为什么必须拆开：岗位名称反映**岗位性质**（强信号、公司不会乱写），
# 专业要求只反映**准入门槛**（弱信号、常写宽口径）。
# 混在一个词表里累加，就必然出现「客服岗因为专业列得多而压过算法岗」。
#
# ---- 通道一：岗位方向词表（只作用于岗位名称，取最高命中权重，不累加）----
# 为什么不累加：岗位名称通常只表达一个方向，「数据分析/软件开发管培生」
# 同时命中「数据分析」和「开发」，累加会重复计权。取 max 更稳。

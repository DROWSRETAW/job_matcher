# ---- 专指度衰减：专业字段命中的词越多，单个词贡献越低 ----
# 理由：列 1 个专业 = 精准定向（强信号）；列 40 个 = 无偏好（弱信号）。
# 线性累加会让「无偏好」的岗位反而拿高分。用几何衰减 + 专指度系数修正。
MAJOR_DECAY = 0.7            # 第 i 个命中词的贡献 = weight * MAJOR_DECAY^(i-1)
MAJOR_CHANNEL_CAP = 15       # 专业准入分封顶
                             # 为什么是 15（= B 级上界）：
                             #   专业要求只代表「能不能过门槛」，不代表「岗位对口」。
                             #   封顶若高过 A 级下限（16），就会出现「财务岗因为在专业里
                             #   点名了信息与计算科学，分数超过算法工程师」——实测发生过。
                             #   封顶在 15，单靠专业最多到 B 级；要进 A/S 必须有方向分配合。
MAJOR_SPECIFICITY_FULL = 4   # 命中词数 ≤ 此值视为「精准定向」，系数 1.0；
                             # 超出则系数 = 该值 / 命中词数

